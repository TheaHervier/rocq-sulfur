(** Implementation of the [Sulfur Judgment] command.

  [Sulfur Judgment R d] expects [R] to be a new identifier and [d : jdg_desc] to
  be a judgment description over a syntax generated by [Sulfur Syntax].
  It declares [R] as an inductive relation whose constructors are the rules of
  [d] (after a variable rule), and proves it sound and complete with respect to
  the judgment signature derived from [d], then stable under substitution.

  Everything is stated and proved in [theories/JdgDesc.v]:
  this file only computes the constructor types by reduction, and instantiates
  the generic lemmas.
*)

open Prelude
module C = Constants

(** A rule: term, name, names of meta-variables. *)
type rule = {
  r_term : EConstr.t ;
  r_name : string ;
  r_binders : string list
}

(** The names of the [n] meta-variables of a rule, read off the HOAS binders of
  its conclusion [λ p, snd (happly sg ps 0 (λ x1 ... xn, _) p)];
  or use [x1 ... xn] when they are not available.
*)
let binder_names (n : int) (concl : EConstr.t) : string list m =
  let* env = get_env in
  let* sigma = get_sigma in
  let default = List.init n (fun i -> "x" ^ string_of_int (i + 1)) in
  let is_happly = EConstr.isRefX env sigma (Lazy.force C.Jdg.happly) in
  let _, body = EConstr.decompose_lambda sigma concl in
  let _, args = EConstr.decompose_app sigma body in
  let happly = if Array.length args = 3 then args.(2) else body in
  match EConstr.decompose_app sigma happly with
  | h, [| _ ; _ ; _ ; _ ; f ; _ |] when is_happly h ->
    let bs = List.rev (fst (EConstr.decompose_lambda sigma f)) in
    if List.length bs <> n then ret default
    else (
      let name (na, _) =
        match na.Context.binder_name with
        | Names.Name id -> Names.Id.to_string id
        | _ -> "x"
      in
      ret (List.map name bs)
    )
  | _ -> ret default

let decode_rule (t : EConstr.t) : rule m =
  decode "a rule"
    [
      C.Jdg.build_rule_desc, fun a ->
        let* r_name = decode_string a.(1) in
        let* ps = decode_list a.(2) in
        let* r_binders = binder_names (List.length ps) a.(4) in
        ret { r_term = t ; r_name ; r_binders }
    ]
    t

(** The signature of a description, from its type [jdg_desc sg]. *)
let decode_sig (desc_ty : EConstr.t) : EConstr.t m =
  let what = "a judgment description" in
  decode what
    [
      C.list, fun a ->
        decode what [ C.Jdg.rule_desc, fun a -> ret a.(0) ] a.(0)
    ]
    desc_ty

(** The values of the fields of a [ConcreteSyntax] instance, except [cctor]. *)
let decode_cs_ops (cs : EConstr.t) : EConstr.t list m =
  decode "a ConcreteSyntax instance"
    [ C.CS.build, fun a -> ret [ a.(2) ; a.(3) ; a.(4) ; a.(5) ; a.(6) ] ]
    cs

let generate_desc (name : Names.Id.t) (desc : EConstr.t) : unit =
  let sname = Names.Id.to_string name in
  let mk s = Names.Id.of_string_soft (sname ^ s) in
  (* The signature of the description, the term type, the instance and its
     laws. *)
  let sg, ty, cs, cl, rules, transparent =
    monad_run begin
      let* desc_ty = typecheck desc None in
      let* sg = decode_sig desc_ty in
      let* ty = fresh_evar None in
      let* cs = resolve_tc (apps (mkglob' C.CS.typ) [| sg ; ty |]) in
      let* sigma = get_sigma in
      let ty = Evarutil.nf_evar sigma ty in
      let* cl = resolve_tc (apps (mkglob' C.CS.laws) [| sg ; ty ; cs |]) in
      let* rules = decode_list desc in
      let* rules = List.monad_map decode_rule rules in
      (* The constants which stay folded in the statements: the description, the
        operations of the syntax, the renamings, the generic judgment [J],
        and [Nat.sub] which would otherwise pollute [csub]. *)
      let* ops = decode_cs_ops cs in
      let* opaque = List.monad_map head_const (desc :: ops) in
      let opaque =
        List.filter_map (fun c -> c) opaque @
        List.map (fun g -> const_of_ref (Lazy.force g)) [
          C.rid ;
          C.rshift ;
          C.rcons ;
          C.rcomp ;
          C.up_ren ;
          C.Jdg.j ;
          C.sub
        ]
      in
      (* The constants the statements may unfold: those reachable from the
        library's definitions and the instance, but not those of the user's
        parameters. *)
      let jdg s = apps (mkglob' s) [| sg ; ty ; cs |] in
      let* transparent =
        constants_closure (
          jdg C.Jdg.rule_desc_type :: jdg C.Jdg.var_rule_type ::
          List.map mkglob'
            [ C.Jdg.hrule ; C.Jdg.hctor ; C.Jdg.hjdg ]
        )
      in
      let transparent =
        List.filter (fun c -> not (List.mem c opaque)) transparent
      in
      ret (sg, ty, cs, cl, rules, transparent)
    end
  in
  let list_ty = app (mkglob' C.list) ty in
  let rule_desc_ty = app (mkglob' C.Jdg.rule_desc) sg in
  let jdg s = apps (mkglob' s) [| sg ; ty ; cs |] in
  (* The constructor types of a relation [r]: the reduced [var_rule_type] and
    [rule_desc_type], with the meta-variables named as in the description. *)
  let var_type (r : EConstr.t) : EConstr.t m =
    reduce_only transparent (app (jdg C.Jdg.var_rule_type) r)
  in
  let rule_type (r : EConstr.t) (rd : rule) : EConstr.t m =
    let* t =
      prod "Γ" list_ty @@ fun g ->
        ret @@
        apps (jdg C.Jdg.rule_desc_type) [| r ; rd.r_term ; EConstr.mkVar g |]
    in
    let* t = reduce_only transparent t in
    rename_binders (None :: List.map (fun x -> Some x) rd.r_binders) t
  in
  (* The inductive. *)
  let arity = arrow list_ty (arrow ty (arrow ty EConstr.mkProp)) in
  let ctor_names =
    mk "_var" :: List.map (fun rd -> Names.Id.of_string_soft rd.r_name) rules
  in
  let ctor_types =
    (fun ind -> var_type (EConstr.mkVar ind)) ::
    List.map (fun rd ind -> rule_type (EConstr.mkVar ind) rd) rules
  in
  let ind = monad_run @@ declare_ind name arity ctor_names ctor_types in
  let r = mkind ind in
  let ctor i = mkctor (ind, i) in
  let stmt s = ret @@ apps (jdg s) [| desc ; r |] in
  (* [R_wf : wf_desc d], using tactic [JdgDesc.wf_desc_tac]. *)
  let wf =
    lemma (sname ^ "_wf")
      (ret @@ apps (mkglob' C.Jdg.wf_desc) [| sg ; desc |])
      (run_ltac "JdgDesc" "wf_desc_tac" [])
  in
  (* [R_rules : rules_type d R], the [Forall] built from the constructors. *)
  let rules_lemma =
    let pred =
      monad_run begin
        lambda "rd" rule_desc_ty @@ fun rd ->
        prod "Γ" list_ty @@ fun g ->
        ret @@
        apps (jdg C.Jdg.rule_desc_type) [|
          r ;
          EConstr.mkVar rd ;
          EConstr.mkVar g
        |]
      end
    in
    let cons rd l = apps (mkglob' C.cons) [| rule_desc_ty ; rd.r_term ; l |] in
    let rec build i = function
      | [] -> apps (mkglob' C.Jdg.forall_nil) [| rule_desc_ty ; pred |]
      | rd :: rest ->
          let rest_list =
            List.fold_right cons rest (app (mkglob' C.nil) rule_desc_ty)
          in
          apps (mkglob' C.Jdg.forall_cons) [|
            rule_desc_ty ;
            pred ;
            rd.r_term ;
            rest_list ;
            ctor (i + 2); build (i + 1) rest
          |]
    in
    lemma (sname ^ "_rules")
      (stmt C.Jdg.rules_type)
      (Tactics.exact_check (build 0 rules))
  in
  (* [R_sound : sound_jdg d R], from the induction principle of [R], whose type
    is convertible to [ind_type d R]. *)
  let sound =
    let scheme =
      Nametab.locate_constant (Libnames.qualid_of_ident (mk "_ind"))
    in
    lemma (sname ^ "_sound")
      (stmt C.Jdg.sound_jdg)
      (Tactics.exact_check (
        apps (jdg C.Jdg.sound_of_ind) [|
          desc ;
          cl ;
          r ;
          mkconst scheme
        |]
      ))
  in
  (* [R_complete : complete_jdg d R]. *)
  let complete =
    lemma (sname ^ "_complete")
      (stmt C.Jdg.complete_jdg)
      (Tactics.exact_check (
        apps (jdg C.Jdg.jdg_complete) [|
          desc ;
          cl ;
          r ;
          ctor 1 ;
          mkconst rules_lemma ;
          mkconst wf
        |]
      ))
  in
  (* [R_subst : preserve_subst_jdg R], stated with [csubstitute] unfolded. *)
  let _subst =
    let stmt =
      let* cs_const = head_const cs in
      let transp = List.map (fun g -> const_of_ref (Lazy.force g)) [
        C.Jdg.preserve_subst_jdg ;
        C.CS.csubstitute
      ] in
      let transp = match cs_const with Some c -> c :: transp | None -> transp in
      reduce_only transp (app (jdg C.Jdg.preserve_subst_jdg) r)
    in
    lemma (sname ^ "_subst") stmt
      (Tactics.exact_check (
        apps (jdg C.Jdg.gen_preserve_subst) [|
          desc ;
          cl ;
          r ;
          mkconst sound ;
          mkconst complete
        |]
      ))
  in
  ()

(** [Sulfur Judgment R d] with [d] a Gallina expression. *)
let generate (name : Names.Id.t) (desc : Constrexpr.constr_expr) : unit =
  generate_desc name (monad_run (pretype desc))

